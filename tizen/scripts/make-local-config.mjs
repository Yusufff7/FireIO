#!/usr/bin/env node
// Writes tizen/<app>/config.local.js from src/storage/localDefaults.ts, so
// the Tizen app uses the same addon URLs as the Fire TV app. The output is
// gitignored for the same reason localDefaults.ts is: an addon URL usually
// embeds a personal API key.
//
// Usage: node tizen/scripts/make-local-config.mjs [app-folder]   (default: poc)

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const app = process.argv[2] || 'poc';

let source;
try {
  source = readFileSync(join(root, 'src/storage/localDefaults.ts'), 'utf8');
} catch {
  console.error('No src/storage/localDefaults.ts — copy localDefaults.example.ts and add your addon URLs first.');
  process.exit(1);
}

const listOf = name => {
  const m = source.match(new RegExp(`${name}\\s*:\\s*\\[([\\s\\S]*?)\\]`));
  return m ? [...m[1].matchAll(/'(https?:\/\/[^']+)'/g)].map(x => x[1]) : [];
};

const config = {
  streamAddonUrls: listOf('streamAddonUrls'),
  backupStreamAddonUrls: listOf('backupStreamAddonUrls'),
  useBackup: false,
};

const out = join(root, 'tizen', app, 'config.local.js');
writeFileSync(out, `// Generated by tizen/scripts/make-local-config.mjs — do not commit.\nwindow.FIREIO_CONFIG = ${JSON.stringify(config, null, 2)};\n`);
console.log(`wrote ${out}: ${config.streamAddonUrls.length} main, ${config.backupStreamAddonUrls.length} backup addons`);
